#!/usr/bin/env python3
"""Measure full-fuzz loudness for every type/voicing and write core/levelcal.h so they all match."""
import sys, re, subprocess, os
sys.path.insert(0, os.path.dirname(__file__))
import analyze as A, sweep as W
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = -12.0
def build():
    subprocess.run(['g++', '-std=c++17', '-O2', '-o', A.RENDER, ROOT + '/tools/render.cpp'], check=True)
def measure():
    p = A.SCR + '/tone.wav'; W.tone_wav(p, amp=10 ** (-6 / 20)); out = []
    for t in (0, 1):
        row = []
        for v in (0, 1, 2):
            (sr, x), o = A.render(['fuzz=1', 'volume=0.5', 'tail=0.2', 'type=%d' % t, 'voicing=%d' % v], inp=p)
            f, th, rms = W.thd(x); row.append(20 * __import__('math').log10(rms))
        out.append(row)
    return out
def write(tbl, lift=10.0):
    open(ROOT + '/core/levelcal.h', 'w').write('''// generated by tools/calibrate.py - loudness trims (dB) so that full fuzz at the middle volume setting lands at the same level
// for every transistor type and voicing. Rows: germanium, silicon. Columns: FAT, ZONK, VIN.
#pragma once
namespace verdigris {
constexpr double kLevelTrimDb[2][3] = {{%.2f, %.2f, %.2f}, {%.2f, %.2f, %.2f}};
constexpr double kCleanLiftDb = %.1f; // extra volume at the clean end of the fuzz knob (fades out toward full fuzz)
} // namespace verdigris
''' % (tbl[0][0], tbl[0][1], tbl[0][2], tbl[1][0], tbl[1][1], tbl[1][2], lift))
if __name__ == '__main__':
    write([[0] * 3, [0] * 3]); build(); m = measure()
    print('before:', [['%.1f' % v for v in r] for r in m])
    tbl = [[TARGET - v for v in r] for r in m]; write(tbl); build(); m2 = measure()
    print('after: ', [['%.1f' % v for v in r] for r in m2]); print('trims:', [['%.2f' % v for v in r] for r in tbl])
