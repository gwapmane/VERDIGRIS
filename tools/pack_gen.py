#!/usr/bin/env python3
"""Writes core/presets_factory.h from the readable table in tools/presets_table.py. Run:  python3 tools/pack_gen.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
PATS=['Off','Chop','Off-beat','Gallop','Heartbeat','Bar start','Late entry','Build','Fade out','Syncopated','Clave','Breath','Stutter','Pulse train','Scatter','Dust']
STEPS=['1/16','1/8 triplet','1/8','1/4 triplet','1/4','1/2','1 bar','2 bars']
SYNCS=['Off','8 bars','4 bars','2 bars','1 bar','2 beats','1 beat','1/2 beat','1/4 beat']
TYPE=['Ge','Si']; VOIC=['Fat','Zonk','Vin']; SHAPE=['sine','tri','saw','rand']
SIDE=['octave','starve','chop','crush','wash','swell']
RAMPT=['fuzz','bias','tone','supply','mix']
# order = the order the plugin stores a preset in (power, trims and tempo are deliberately not here)
IDS=['fuzz','bias','volume','type','voicing','octave','starve','chop','crush','wash','swell','octAmt','starveAmt','chopPattern',
     'crushAmt','washMix','swellTime','sag','chopStep','chopDepth','chopSmooth','washDecay','tone','gate','mix','hfe','temp','drift',
     'spread','pickup','guitar','lowcut','mids','supply','rampRate','rampDepth','rampShape','rampSync','rampFuzz','rampBias',
     'rampTone','rampSupply','rampMix']
D=dict(fuzz=.6,bias=.5,volume=.5,type='Ge',voicing='Vin',on=[],octAmt=.6,starveAmt=.6,pattern='Chop',crushAmt=.5,washMix=.4,swellTime=.5,
       sag=.3,step='1/8',cdepth=1,csmooth=.2,washDecay=.5,tone=.55,gate=0,mix=1,hfe=.5,temp=.4,drift=0,spread=.3,pickup=.5,guitar=1,
       lowcut=0,mids=.5,supply=.88,rrate=.4,rdepth=0,rshape='sine',rsync='Off',ramp=[])
def norm(i,n): return i/(n-1)
try:
    from vol_auto import VOL
except Exception:
    VOL={}
def enc(p,name=None):
    m=dict(D)
    if name in VOL: m['volume']=VOL[name]
    m.update(p); v=[]
    v+=[m['fuzz'],m['bias'],m['volume'],norm(TYPE.index(m['type']),2),norm(VOIC.index(m['voicing']),3)]
    for s in SIDE: v.append(1.0 if s in m['on'] else 0.0)
    v+=[m['octAmt'],m['starveAmt'],norm(PATS.index(m['pattern']),16),m['crushAmt'],m['washMix'],m['swellTime'],m['sag'],
        norm(STEPS.index(m['step']),8),m['cdepth'],m['csmooth'],m['washDecay'],m['tone'],m['gate'],m['mix'],m['hfe'],m['temp'],
        m['drift'],m['spread'],m['pickup'],m['guitar'],m['lowcut'],m['mids'],m['supply'],m['rrate'],m['rdepth'],
        norm(SHAPE.index(m['rshape']),4),norm(SYNCS.index(m['rsync']),9)]
    for t in RAMPT: v.append(1.0 if t in m['ramp'] else 0.0)
    assert len(v)==len(IDS),(len(v),len(IDS))
    return v
def render_args(p):
    """the key=value list for tools/render.cpp that matches a preset"""
    m=dict(D); m.update(p)
    a=[]
    for k in ['fuzz','bias','volume','octAmt','starveAmt','crushAmt','washMix','swellTime','sag','chopDepth','chopSmooth','washDecay','tone','gate','mix','hfe','temp','drift','spread','pickup','guitar','lowcut','mids','supply','rampRate','rampDepth']:
        src={'chopDepth':'cdepth','chopSmooth':'csmooth','rampRate':'rrate','rampDepth':'rdepth'}.get(k,k)
        a.append('%s=%s'%(k,m[src]))
    a+=['type=%d'%TYPE.index(m['type']),'voicing=%d'%VOIC.index(m['voicing']),'chopPattern=%d'%PATS.index(m['pattern']),'chopStep=%d'%STEPS.index(m['step']),
        'rampShape=%d'%SHAPE.index(m['rshape']),'rampSync=%d'%SYNCS.index(m['rsync'])]
    for s in SIDE: a.append('%s=%d'%(s,1 if s in m['on'] else 0))
    a.append('rampTargets=%d'%sum(1<<i for i,t in enumerate(RAMPT) if t in m['ramp']))
    return a
if __name__=='__main__':
    from presets_table import P
    out=['// GENERATED by tools/pack_gen.py - edit the table in tools/presets_table.py, not this file.','#pragma once','#include <vector>','','namespace verdigris {',
         'constexpr int kNumSoundIds = %d;'%len(IDS),
         'inline const char* const* soundIdNames() {','    static const char* const n[kNumSoundIds] = {'+', '.join('"%s"'%i for i in IDS)+'};','    return n;','}','',
         'struct FactoryPreset {','    const char *category, *name, *hint;','    float v[kNumSoundIds]; // normalised 0..1, in soundIdNames() order','};','',
         'inline const std::vector<FactoryPreset>& factoryPresets() {','    static const std::vector<FactoryPreset> bank = {']
    for cat,name,hint,kw in P:
        v=enc(kw,name)
        out.append('        {"%s", "%s", "%s", {%s}},'%(cat,name,hint.replace('"','\\"'),', '.join('%.4ff'%x for x in v)))
    out+=['    };','    return bank;','}','} // namespace verdigris','']
    dst=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','core','presets_factory.h')
    open(dst,'w').write('\n'.join(out))
    names=[p[1] for p in P]; assert len(set(names))==len(names)
    print(len(P),'presets')
